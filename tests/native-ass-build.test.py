"""Source-integrity boundaries of the actual native dependency preparer; no network or SDK build."""
import hashlib
import importlib.util
import io
from pathlib import Path
import tarfile
import tempfile
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location('native_ass_builder',
    Path(__file__).resolve().parents[1] / 'scripts/prepare-native-ass.py')
builder = importlib.util.module_from_spec(spec)
spec.loader.exec_module(builder)


class NativeSourceIntegrity(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='cineisle-native-source-')
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        builder.CACHE = self.root / 'cache'
        (builder.CACHE / 'archives').mkdir(parents=True)
        (builder.CACHE / 'sources').mkdir()

    def archive(self, entries):
        archive = self.root / 'test.tar.gz'
        with tarfile.open(archive, 'w:gz') as target:
            for name, value in entries:
                info = tarfile.TarInfo(name)
                data = value.encode()
                info.size = len(data)
                target.addfile(info, io.BytesIO(data))
        checksum = hashlib.sha256(archive.read_bytes()).hexdigest()
        cached = builder.CACHE / 'archives' / (checksum + '.tar.gz')
        cached.write_bytes(archive.read_bytes())
        return cached, {'name': 'libass', 'sha256': checksum, 'url': 'https://example.invalid/never-used'}

    def test_verified_archive_extracts_and_reuses_the_same_source(self):
        _, record = self.archive([('source/a.c', 'fixed source'), ('source/docs/COPYING', 'license')])
        directory = builder.source(record, True, {})
        self.assertEqual((directory / 'a.c').read_text(), 'fixed source')
        self.assertEqual((directory / 'docs/COPYING').read_text(), 'license')
        self.assertEqual(builder.source(record, True, {}), directory)

    def test_changed_source_cache_is_rejected_instead_of_recompiled(self):
        _, record = self.archive([('source/a.c', 'fixed source')])
        directory = builder.source(record, True, {})
        (directory / 'a.c').write_text('changed after extraction')
        with self.assertRaisesRegex(RuntimeError, 'extracted source changed'):
            builder.source(record, True, {})

    def test_generated_bytecode_is_ignored_but_new_source_files_still_fail_integrity(self):
        _, record = self.archive([('source/helper.py', 'fixed source')])
        directory = builder.source(record, True, {})
        generated = directory / '__pycache__'
        generated.mkdir()
        (generated / 'helper.cpython-314.pyc').write_bytes(b'generated bytecode')
        self.assertEqual(builder.source(record, True, {}), directory)
        (generated / 'unexpected.py').write_text('new source')
        with self.assertRaisesRegex(RuntimeError, 'extracted source changed'):
            builder.source(record, True, {})

    def test_unchanged_active_prefix_keeps_its_timestamp_and_new_prefix_is_atomic(self):
        first = self.root / 'first'
        builder.activate(first)
        active = builder.CACHE / 'active-prefix.txt'
        modified = active.stat().st_mtime_ns
        builder.activate(first)
        self.assertEqual(active.stat().st_mtime_ns, modified)
        second = self.root / 'second'
        builder.activate(second)
        self.assertEqual(active.read_text(), str(second) + '\n')
        self.assertFalse((builder.CACHE / 'active-prefix.tmp').exists())

    def test_corrupt_archive_is_rejected_before_extraction(self):
        archive, record = self.archive([('source/a.c', 'fixed source')])
        archive.write_bytes(b'corrupt')
        with self.assertRaisesRegex(RuntimeError, 'cached archive fingerprint mismatch'):
            builder.source(record, True, {})
        self.assertEqual(list((builder.CACHE / 'sources').iterdir()), [])

    def test_missing_archive_offline_never_invokes_a_download(self):
        with self.assertRaisesRegex(RuntimeError, 'unavailable offline'):
            builder.source({'name': 'libass', 'sha256': 'a' * 64}, True, {})

    def test_bad_download_is_not_published_or_extracted(self):
        record = {'name': 'libass', 'sha256': 'a' * 64, 'url': 'https://example.invalid/source'}
        def download(args, _env):
            Path(args[args.index('--output') + 1]).write_bytes(b'wrong response')
        with patch.object(builder, 'run', side_effect=download):
            with self.assertRaisesRegex(RuntimeError, 'download fingerprint mismatch'):
                builder.source(record, False, {})
        self.assertFalse((builder.CACHE / 'archives' / ('a' * 64 + '.tar.gz')).exists())
        self.assertEqual(list((builder.CACHE / 'sources').iterdir()), [])

    def test_verified_download_is_published_and_then_available_offline(self):
        archive, record = self.archive([('source/a.c', 'fixed source')])
        data = archive.read_bytes()
        archive.unlink()
        def download(args, _env):
            self.assertEqual(args[-1], record['url'])
            Path(args[args.index('--output') + 1]).write_bytes(data)
        with patch.object(builder, 'run', side_effect=download) as transport:
            directory = builder.source(record, False, {})
            self.assertEqual(builder.source(record, True, {}), directory)
            self.assertEqual(transport.call_count, 1)

    def test_path_escape_and_multiple_roots_are_rejected(self):
        for number, entries in enumerate([[('../escaped', 'bad')], [('/absolute', 'bad')],
                [('source/../../escaped', 'bad')], [('one/a', 'a'), ('two/b', 'b')]]):
            archive, _ = self.archive(entries)
            with self.assertRaisesRegex(RuntimeError, 'unsafe source|multiple roots'):
                builder.extract(archive, self.root / ('extract-' + str(number)))
        self.assertFalse((self.root / 'escaped').exists())

    def test_archive_links_are_not_followed_or_published(self):
        archive = self.root / 'links.tar.gz'
        with tarfile.open(archive, 'w:gz') as target:
            for kind in [tarfile.SYMTYPE, tarfile.LNKTYPE]:
                info = tarfile.TarInfo('source/link-' + kind.decode())
                info.type = kind
                info.linkname = '../../outside'
                target.addfile(info)
            info = tarfile.TarInfo('source/real')
            info.size = 2
            target.addfile(info, io.BytesIO(b'ok'))
        destination = self.root / 'links'
        builder.extract(archive, destination)
        self.assertEqual(sorted(p.name for p in destination.iterdir()), ['.source-files.json', 'real'])


if __name__ == '__main__':
    unittest.main()
